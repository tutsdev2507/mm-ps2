#!/usr/bin/env python3
"""
Generate C placeholders for every symbol defined by the extracted asset
objects, so the ported game can be linked WITHOUT embedding the assets.

Why: the extracted N64 assets (objects, scenes, archives, interface,
misc, boot) are compiled as C arrays.  Linked flat they occupy 34.8 MB of
.data, which cannot fit the PS2's 32 MiB of RAM together with the code.
On the N64 those segments are NOLOAD and are DMA'd from ROM on demand,
which is what platform/ps2/{segloader.c,dmadata_ps2.c} do for the port.

This script reads the symbol table of each asset object and emits one
placeholder per symbol.  Symbol *addresses* are meaningless here - they
exist only so the link resolves; the real data is loaded at runtime into
the segment window the game asks for.

Usage:
  python3 scripts/gen_asset_stubs.py <objdir> <output.c>
"""
import os
import re
import subprocess
import sys

NM = 'mips64r5900el-ps2-elf-nm'
SKIP = re.compile(r'(__os|_gp|_fdata|_ftext|_end|_edata|_fbss|_stack)')


def symbols_of(obj):
    out = subprocess.run([NM, '--defined-only', obj],
                         capture_output=True, text=True)
    if out.returncode != 0:
        return []
    syms = []
    for line in out.stdout.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        addr, kind, name = parts[0], parts[1], parts[2]
        if kind in 'tT' or SKIP.search(name):
            continue
        if name.startswith('.'):
            continue
        syms.append((name, kind))
    return syms


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    objdir, out = sys.argv[1], sys.argv[2]

    seen = set()
    entries = []
    for root, _dirs, files in os.walk(objdir):
        for fn in sorted(files):
            if not fn.endswith('.o'):
                continue
            path = os.path.join(root, fn)
            rel = os.path.relpath(path, objdir)
            if not rel.startswith('extracted/'):
                continue
            for name, kind in symbols_of(path):
                if name in seen:
                    continue
                seen.add(name)
                # BSS-sized placeholder: real size comes from the runtime
                # loader, this only has to be a distinct address.
                if kind in 'bB':
                    entries.append('u8 %s[8] __attribute__((used, aligned(16)));'
                                   % name)
                else:
                    entries.append('u8 %s[8] __attribute__((used, aligned(16)));'
                                   % name)

    with open(out, 'w') as f:
        f.write('/* Generated by scripts/gen_asset_stubs.py - do not edit. */\n')
        f.write('/*\n'
                ' * Placeholders for the extracted N64 assets.  The port loads\n'
                ' * them at runtime (platform/ps2/segloader.c + dmadata_ps2.c),\n'
                ' * so the link only needs the symbols to exist.\n'
                ' */\n\n')
        f.write('\n'.join(entries))
        f.write('\n')
    print('wrote %s: %d symbols' % (out, len(entries)))


if __name__ == '__main__':
    main()
