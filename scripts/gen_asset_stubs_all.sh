#!/bin/sh
# Gera stubs de assets a partir de TODOS os objetos de asset (extracted + assets)
set -e
OBJDIR="${1:-/src/third_party/mm/build/ee/obj}"
OUT="${2:-/src/third_party/mm/build/ee/asset_stubs_all.c}"
NM=mips64r5900el-ps2-elf-nm
TMP=$(mktemp)
# Varre extracted e assets
find "$OBJDIR" -name '*.o' \
  \( -path '*/extracted/*' -o -path '*/assets/*' \) \
  -print0 2>/dev/null | xargs -0 -r "$NM" -A --defined-only 2>/dev/null > "$TMP" || true

{
  echo '/* Generated by gen_asset_stubs_all.sh - do not edit. */'
  echo
  awk '
    {
      name = $NF
      type = $(NF-1)
      if (type == "t" || type == "T") next
      if (name ~ /^\./) next
      if (name ~ /^(_gp|_fdata|_ftext|_end|_edata|_fbss|_stack)$/) next
      if (name ~ /^__os/) next
      if (seen[name]++) next
      printf "unsigned char %s[8] __attribute__((used, aligned(16)));\n", name
    }
  ' "$TMP" | sort -u
} > "$OUT"
rm -f "$TMP"
echo "wrote $OUT: $(wc -l < "$OUT") lines"
