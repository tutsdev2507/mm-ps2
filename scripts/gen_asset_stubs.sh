#!/bin/sh
# Shell equivalent of gen_asset_stubs.py (the ps2dev rootfs has no python3).
# Emits one 8-byte placeholder per symbol DEFINED by the extracted asset
# objects, so the code image links without embedding the assets.  The real
# data is loaded at runtime by platform/ps2/{segloader.c,dmadata_ps2.c}.
#
# Runs INSIDE the proot rootfs:  sh /src/scripts/gen_asset_stubs.sh [OBJDIR] [OUT]
set -e
OBJDIR="${1:-/src/third_party/mm/build/ee/obj_o2}"
OUT="${2:-/src/third_party/mm/build/ee/asset_stubs.c}"
NM=mips64r5900el-ps2-elf-nm

TMP=$(mktemp)
find "$OBJDIR/extracted" -name '*.o' -print0 2>/dev/null \
  | xargs -0 -r "$NM" -A --defined-only 2>/dev/null > "$TMP" || true

{
  echo '/* Generated by scripts/gen_asset_stubs.sh - do not edit. */'
  echo '/*'
  echo ' * Placeholders for the extracted N64 assets.  The port loads them at'
  echo ' * runtime (platform/ps2/segloader.c + dmadata_ps2.c), so the link only'
  echo ' * needs the symbols to exist.'
  echo ' */'
  echo
  awk '
    {
      # nm -A output:  "<obj>:<addr> <type> <name>"
      name = $NF
      type = $(NF-1)
      if (type == "t" || type == "T") next          # code
      if (name ~ /^\./) next                        # local/section
      if (name ~ /^(_gp|_fdata|_ftext|_end|_edata|_fbss|_stack)$/) next
      if (name ~ /^__os/) next
      if (seen[name]++) next
      printf "unsigned char %s[8] __attribute__((used, aligned(16)));\n", name
    }
  ' "$TMP" | sort -u
} > "$OUT"

rm -f "$TMP"
echo "wrote $OUT: $(wc -l < "$OUT") lines"
