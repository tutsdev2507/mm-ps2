#!/usr/bin/env python3
"""
Generate a PS2-specific gDmaDataTable with the *real* VROM/ROM values taken
from the extracted dmadata binary.

The decomp builds gDmaDataTable from linker symbols (_<name>SegmentRomStart)
that only exist when the original segmented linker layout is used. For the
PS2 port we use a flat ROM file (mass0:/MMPS2/rom.z64) and read by physical
offset, so the table must carry the literal vrom/rom numbers instead.
"""
import os
import struct

MM = '/storage/emulated/0/Download/mm-ps2/third_party/mm'
DMADATA = os.path.join(MM, 'extracted', 'n64-us', 'baserom', 'dmadata')
OUT = '/storage/emulated/0/Download/mm-ps2/platform/ps2/dmadata_ps2.c'
OUT_H = '/storage/emulated/0/Download/mm-ps2/platform/ps2/dmadata_ps2.h'


def main():
    data = open(DMADATA, 'rb').read()
    n = len(data) // 16
    entries = []
    for i in range(n):
        vs, ve, rs, re_ = struct.unpack_from('>IIII', data, i * 16)
        if vs == 0 and ve == 0 and rs == 0 and re_ == 0:
            break
        entries.append((vs, ve, rs, re_))

    with open(OUT, 'w') as f:
        f.write('/* Generated by scripts/gen_dmadata_ps2.py - do not edit. */\n')
        f.write('#include "dmadata_ps2.h"\n\n')
        f.write('DmaEntry gDmaDataTable[] = {\n')
        for vs, ve, rs, re_ in entries:
            f.write('    { { 0x%08Xu, 0x%08Xu }, 0x%08Xu, 0x%08Xu },\n' % (vs, ve, rs, re_))
        f.write('    { { 0u, 0u }, 0u, 0u },\n')
        f.write('};\n')
        f.write('size_t gDmaTableEntryCount = %d;\n' % len(entries))

    with open(OUT_H, 'w') as f:
        f.write('#ifndef DMADATA_PS2_H\n#define DMADATA_PS2_H\n')
        f.write('#include "z64dma.h"\n')
        f.write('extern size_t gDmaTableEntryCount;\n')
        f.write('#endif\n')

    print('wrote', len(entries), 'entries')


if __name__ == '__main__':
    main()
