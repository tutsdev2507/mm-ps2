#!/usr/bin/env python3
"""
Generate include/tables/dmadata/dmadata_table_spec.h for the PS2 build.

src/dmadata/dmadata.c includes tables/dmadata_table.h, which includes
dmadata/dmadata_table_spec.h.  Upstream that file is produced by the N64
build from `spec/spec` and expands to one DEFINE_DMA_ENTRY(name, "name")
per ROM segment, in dmadata order.

For the port we only need the *names*: the VROM/ROM numbers that the real
table would carry come from platform/ps2/dmadata_ps2.c (generated by
gen_dmadata_ps2.py from the extracted dmadata binary), which is the table
the PS2 build actually links.
"""
import os
import re
import struct
import sys

MM = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                  'third_party', 'mm')
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(MM, 'spec', 'spec')
DMADATA = os.path.join(MM, 'extracted', 'n64-us', 'baserom', 'dmadata')
OUT = os.path.join(REPO, 'include', 'tables', 'dmadata',
                   'dmadata_table_spec.h')


def spec_segments(path):
    """Yield (name, noload) for every beginseg block in the spec file."""
    text = open(path, encoding='latin-1', errors='replace').read()
    for block in re.findall(r'beginseg(.*?)endseg', text, re.S):
        m = re.search(r'name\s+"([^"]+)"', block)
        if not m:
            continue
        noload = bool(re.search(r'flags\s+.*NOLOAD', block))
        yield m.group(1), noload


def dmadata_count(path):
    data = open(path, 'rb').read()
    n = 0
    for i in range(0, len(data), 0x10):
        chunk = data[i:i + 0x10]
        if len(chunk) != 0x10:
            break
        vs, ve, rs, re_ = struct.unpack('>IIII', chunk)
        if vs == 0 and ve == 0 and rs == 0 and re_ == 0:
            break
        n += 1
    return n


def main():
    if not os.path.exists(SPEC):
        print('missing spec:', SPEC)
        sys.exit(1)
    if not os.path.exists(DMADATA):
        print('missing dmadata:', DMADATA)
        sys.exit(1)

    names = [n for n, noload in spec_segments(SPEC) if not noload]
    total = dmadata_count(DMADATA)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write('/* Generated by scripts/gen_dmadata_spec.py - do not edit. */\n')
        f.write('#ifndef DMADATA_TABLE_SPEC_H\n')
        f.write('#define DMADATA_TABLE_SPEC_H\n\n')
        f.write('/*\n')
        f.write(' * One entry per dmadata slot, named after the spec segment that\n')
        f.write(' * occupies it.  src/dmadata/dmadata.c redefines the macros before\n')
        f.write(' * including this, so only the invocation list is emitted here.\n')
        f.write(' */\n\n')
        for i in range(total):
            nm = names[i] if i < len(names) else 'seg_%03d' % i
            f.write('DEFINE_DMA_ENTRY(%s, "%s")\n' % (nm, nm))
        f.write('\n#endif\n')

    print('wrote %s: %d entries (spec loadable segments: %d)'
          % (OUT, total, len(names)))


if __name__ == '__main__':
    main()
